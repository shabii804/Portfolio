// v34 — projects pin system schema:
//   projects[] gains `pinned` (pins the card to the top of /projects)
//   settings gains pinnedRepos[] / hiddenRepos[] / repoOverrides{}
// Seeds Farooq Agencies pinned:true (already first — order unchanged, badge demo).
// Regenerates src/data/portfolio.js with the exact renderPortfolioModule template.
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const jPath = path.join(ROOT, "src/data/content.json");
const j = JSON.parse(fs.readFileSync(jPath, "utf8"));

// 1) pinned flag on every curated project (Farooq Agencies = true)
let seeded = null;
for (const p of j.projects || []) {
  p.pinned = p.pinned === true || /farooq/i.test(p.title || "");
  if (p.pinned) seeded = p.title;
}

// 2) settings defaults for the GitHub archive controls
j.settings = {
  ...(j.settings || {}),
  pinnedRepos: Array.isArray(j.settings?.pinnedRepos) ? j.settings.pinnedRepos : [],
  hiddenRepos: Array.isArray(j.settings?.hiddenRepos) ? j.settings.hiddenRepos : [],
  repoOverrides:
    j.settings?.repoOverrides && typeof j.settings.repoOverrides === "object"
      ? j.settings.repoOverrides
      : {},
};

fs.writeFileSync(jPath, JSON.stringify(j, null, 2) + "\n");

// 3) regenerate portfolio.js — byte-identical template to
//    server/admin/store.js renderPortfolioModule()
const mod = `// ⚠️ AUTO-GENERATED by the portfolio Admin panel (/admin) — do not edit by hand.
// Canonical data lives in src/data/content.json; this module is regenerated on
// every admin save so the site build and the AI chatbot fact sheet stay in sync.
export const content = ${JSON.stringify(j, null, 2)};

export const defaultProjects = content.projects;
export const defaultSkills = content.skills;
export const defaultPersonal = content.personal;
export const defaultExperience = content.experience;
export const defaultJourney = content.journey;
export const defaultServices = content.services;
export const defaultCertificates = content.certificates;
export const contentMeta = content.meta;
`;
fs.writeFileSync(path.join(ROOT, "src/data/portfolio.js"), mod);

console.log("OK — pinned seed:", seeded);
console.log("projects:", (j.projects || []).map((p) => `${p.title}${p.pinned ? " [pinned]" : ""}`).join(" | "));
console.log("settings keys:", Object.keys(j.settings).join(","));
