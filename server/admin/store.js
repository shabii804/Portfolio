// ─────────────────────────────────────────────────────────────────────────────
// Content + message store with three interchangeable drivers:
//
//   supabase (production) — JSON documents + media in Supabase Storage. Saves
//                          go LIVE INSTANTLY (the site fetches /api/content at
//                          runtime); no rebuild needed. When GITHUB_TOKEN is
//                          also set, content.json is best-effort mirrored to
//                          the repo so rebuilds bundle fresh data too.
//   github (production) — reads/writes JSON through the GitHub Contents API.
//                         Saving content commits src/data/content.json AND
//                         regenerates src/data/portfolio.js → Vercel rebuilds.
//   file   (sandbox/dev) — reads/writes the same files directly on disk so
//                          Vite HMR picks up edits instantly.
//
// Canonical data:  src/data/content.json   (pretty JSON, human editable)
// Consumer module: src/data/portfolio.js   (AUTO-GENERATED from the JSON on
//                                           every save — the site + AI
//                                           chatbot fact sheet import this)
// Contact inbox:   data/messages.json      (not imported by the site)
// ─────────────────────────────────────────────────────────────────────────────

import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { error } from "./http.js";
import { ghRead, ghWrite, ghWriteRaw, ghConfig } from "./github.js";
import { sbEnabled, sbReadText, sbWriteText } from "./supabase.js";

const ROOT = path.resolve(fileURLToPath(new URL("../..", import.meta.url))); // → Portfolio/
const CONTENT_FILE = process.env.CONTENT_PATH || "src/data/content.json";
const MESSAGES_FILE = process.env.MESSAGES_PATH || "data/messages.json";

export const storageMode = () =>
  sbEnabled() ? "supabase" : process.env.GITHUB_TOKEN ? "github" : "file";

export function persistenceNotConfigured(err) {
  return err?.message === "PERSISTENCE_NOT_CONFIGURED";
}

// Map filesystem write failures on read-only hosts (Vercel serverless =
// EROFS on /var/task/**) onto the canonical PERSISTENCE_NOT_CONFIGURED error
// so sendStoreError answers with the actionable 503 instead of a raw OS error.
export function mapStorageError(err) {
  if (err && ["EROFS", "EACCES", "EPERM"].includes(err.code)) {
    return new Error("PERSISTENCE_NOT_CONFIGURED", { cause: err });
  }
  return err;
}

export function sendStoreError(res, err) {
  if (persistenceNotConfigured(err)) {
    return error(
      res,
      503,
      "Persistence is not configured on this deployment. Fix it in one of two ways: (1) /admin → Settings → “Connect GitHub” — paste a token, works instantly from your browser; or (2) set GITHUB_TOKEN (GitHub CMS) or SUPABASE_URL + SUPABASE_SERVICE_KEY (instant Supabase CMS) in Vercel → Settings → Environment Variables and redeploy."
    );
  }
  return error(res, 500, err?.message || "Storage error");
}

// Renders canonical JSON as the ES module the site + chatbot import.
export function renderPortfolioModule(content) {
  return `// ⚠️ AUTO-GENERATED by the portfolio Admin panel (/admin) — do not edit by hand.
// Canonical data lives in src/data/content.json; this module is regenerated on
// every admin save so the site build and the AI chatbot fact sheet stay in sync.
export const content = ${JSON.stringify(content, null, 2)};

export const defaultProjects = content.projects;
export const defaultSkills = content.skills;
export const defaultPersonal = content.personal;
export const defaultExperience = content.experience;
export const defaultJourney = content.journey;
export const defaultServices = content.services;
export const contentMeta = content.meta;
`;
}

// ── file driver ──────────────────────────────────────────────────────────────
async function fileRead(rel) {
  try {
    return await fs.readFile(path.join(ROOT, rel), "utf8");
  } catch (err) {
    if (err.code === "ENOENT") return null;
    throw err;
  }
}

async function fileWrite(rel, text) {
  const target = path.join(ROOT, rel);
  await fs.mkdir(path.dirname(target), { recursive: true });
  await fs.writeFile(target, text, "utf8");
}

// ── content ──────────────────────────────────────────────────────────────────
export async function readContent() {
  if (storageMode() === "supabase") {
    const remote = await sbReadText("data/content.json");
    if (remote) return JSON.parse(remote);
  }
  if (storageMode() === "github") {
    const remote = await ghRead(CONTENT_FILE);
    if (remote) return JSON.parse(remote.text);
  }
  const local = await fileRead(CONTENT_FILE);
  if (local) return JSON.parse(local);
  // Last resort (serverless bundles may omit raw JSON files): use the
  // bundled ES module — api/chat.js already imports from src/ successfully.
  // The specifier is computed so the Vite config bundler cannot trace it
  // (traced imports are watched → admin saves would restart the dev server).
  try {
    const spec = ["..", "..", "src", "data", "portfolio.js"].join("/");
    const mod = await import(/* @vite-ignore */ spec);
    return mod.content ?? null;
  } catch {
    return null;
  }
}

export async function writeContent(content, sections) {
  const json = JSON.stringify(content, null, 2) + "\n";
  const message = `feat(admin): update ${sections.join(", ")} via admin panel`;
  if (storageMode() === "supabase") {
    await sbWriteText("data/content.json", json);
    // Best-effort repo mirror (keeps the build-time bundle fresh on later
    // rebuilds when both drivers are configured). Never blocks the save.
    if (process.env.GITHUB_TOKEN) {
      try {
        await ghWrite(CONTENT_FILE, json, message);
        await ghWrite("src/data/portfolio.js", renderPortfolioModule(content), message);
      } catch {
        /* mirror is optional — Supabase already has the canonical copy */
      }
    }
    return { mode: "supabase", message };
  }
  if (storageMode() === "github") {
    await ghWrite(CONTENT_FILE, json, message);
    await ghWrite("src/data/portfolio.js", renderPortfolioModule(content), message);
    return { mode: "github", message };
  }
  try {
    await fileWrite(CONTENT_FILE, json);
    await fileWrite("src/data/portfolio.js", renderPortfolioModule(content));
  } catch (err) {
    throw mapStorageError(err);
  }
  return { mode: "file", message };
}

// ── contact inbox ────────────────────────────────────────────────────────────
export async function readMessages() {
  let text;
  if (storageMode() === "supabase") {
    text = await sbReadText("data/messages.json");
  } else if (storageMode() === "github") {
    const remote = await ghRead(MESSAGES_FILE);
    text = remote?.text ?? null;
  } else {
    text = await fileRead(MESSAGES_FILE);
  }
  if (!text) return [];
  try {
    const parsed = JSON.parse(text);
    return Array.isArray(parsed) ? parsed : [];
  } catch {
    return [];
  }
}

export async function writeMessages(messages) {
  const json = JSON.stringify(messages, null, 2) + "\n";
  if (storageMode() === "supabase") {
    await sbWriteText("data/messages.json", json);
    return { mode: "supabase" };
  }
  if (storageMode() === "github") {
    // "[skip ci]" → the inbox update does not burn a Vercel build
    await ghWrite(MESSAGES_FILE, json, "[skip ci] chore(admin): update contact inbox");
    return { mode: "github" };
  }
  try {
    await fileWrite(MESSAGES_FILE, json);
  } catch (err) {
    throw mapStorageError(err);
  }
  return { mode: "file" };
}

export { ghConfig, ghWriteRaw };
